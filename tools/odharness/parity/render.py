"""Render-page runner: shows every page of a render suite in both clients, screenshots them, finds the map by
its magenta corner markers, and compares each cell's pixels.

    python -I render.py <suite> [--pages 0,3,5] [--settle S] [--keep]     run live and compare
    python -I render.py <suite> --compare-only                             re-compare the last screenshots

Output: out/render/<suite>/index.html (side by side + diff per cell, failures first) and summary.json.
A cell passes when the share of pixels differing by more than PIX_THRESH in any channel is <= tol[0] and the
mean channel difference is <= tol[1]. Tolerances come from the cell (s.cell(..., tol=)) or DEFAULT_TOL.
"""
import html, json, sys, time
from pathlib import Path

import numpy as np
from PIL import Image

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
sys.stdout.reconfigure(encoding="utf-8", errors="replace")
import gen  # noqa: E402

PIX_THRESH = 24          # a channel difference above this counts the pixel as different
DEFAULT_TOL = (0.02, 3.0)  # (share of differing pixels, mean channel difference)
TILE = 32
VIEW = (25, 17)
CELL = 3 * TILE
OUT = HERE.parent / "out" / "render"


def find_map(img):
    """Top-left pixel of the map inside a window screenshot, from the four magenta 32x32 corner markers."""
    a = np.asarray(img.convert("RGB")).astype(int)
    mask = (a[:, :, 0] == 255) & (a[:, :, 1] == 0) & (a[:, :, 2] == 255)
    ys, xs = np.nonzero(mask)
    if len(xs) < 4 * TILE * TILE * 0.9:
        raise ValueError("corner markers not found")
    x0, x1, y0, y1 = xs.min(), xs.max(), ys.min(), ys.max()
    w, h = x1 - x0 + 1, y1 - y0 + 1
    if (w, h) != (VIEW[0] * TILE, VIEW[1] * TILE):
        raise ValueError(f"map is {w}x{h}, expected {VIEW[0] * TILE}x{VIEW[1] * TILE} (display scaling or zoom?)")
    return x0, y0


def page_code(map_img):
    """The page number shown in the code tile (tile 2,17 = column 1, top row)."""
    r, g, b = map_img.getpixel((TILE + TILE // 2, TILE // 2))[:3]
    return r + 256 * g if b == 77 else None


def cell_box(slot):
    # Matches render_cell_turf(): cell columns span tiles x = 3+3c .. 5+3c, rows y = 1+3r .. 3+3r counted from
    # the bottom (r = 4 - top-based row). Tile (X, Y) starts at pixel ((X-1)*32, (17-Y)*32) of the map.
    c, r_top = slot % 7, slot // 7
    r = 4 - r_top
    left = (3 + 3 * c - 1) * TILE
    top = (VIEW[1] - (3 + 3 * r)) * TILE
    return left, top, left + CELL, top + CELL


def compare(by, od, tol):
    a = np.asarray(by.convert("RGBA")).astype(int)
    b = np.asarray(od.convert("RGBA")).astype(int)
    d = np.abs(a - b)[:, :, :3]
    over = (d.max(axis=2) > PIX_THRESH)
    share, mean = float(over.mean()), float(d.mean())
    tol = tol or DEFAULT_TOL
    heat = np.zeros_like(a[:, :, :3])
    heat[:, :, 0] = np.clip(d.max(axis=2) * 4, 0, 255)
    heat[over] = [255, 255, 0]
    return share <= tol[0] and mean <= tol[1], share, mean, Image.fromarray(heat.astype("uint8"))


def shoot_pages(suite, pages, settle):
    from live import Live
    shots = {}
    with Live(suite) as L:
        for p in pages:
            for attempt in range(4):
                L.cmd_all(cmd="page", n=p)
                time.sleep(settle)
                ok = True
                for e in L.engines:
                    f = L.shot(e, f"page{p}")
                    img = Image.open(f)
                    try:
                        x0, y0 = find_map(img)
                    except ValueError as ex:
                        print(f"{e} page {p}: {ex}")
                        ok = False
                        continue
                    m = img.crop((x0, y0, x0 + VIEW[0] * TILE, y0 + VIEW[1] * TILE))
                    if page_code(m) != p:
                        print(f"{e} page {p}: code tile shows {page_code(m)}, retrying")
                        ok = False
                    shots[(p, e)] = m
                if ok:
                    break
            print(f"page {p}: captured", flush=True)
        errs = {e: {k: v for k, v in L.results(e).items() if k.startswith("cell#")} for e in L.engines}
    return shots, errs


def main(a):
    suite = a[0]
    layout = json.loads((gen.BUILD / suite / "render_layout.json").read_text(encoding="utf-8")) if (gen.BUILD / suite / "render_layout.json").exists() else None
    settle = float(a[a.index("--settle") + 1]) if "--settle" in a else 1.5
    outdir = OUT / suite
    outdir.mkdir(parents=True, exist_ok=True)
    if "--compare-only" in a:
        shots = {}
        for f in outdir.glob("map_p*_*.png"):
            p, e = f.stem[5:].split("_")
            shots[(int(p), e)] = Image.open(f)
        errs = json.loads((outdir / "errors.json").read_text())
    else:
        layout = None  # regenerated by the build inside Live
        from live import Live  # noqa: F401
        import run
        run.build(suite)
        layout = json.loads((gen.BUILD / suite / "render_layout.json").read_text(encoding="utf-8"))
        pages = sorted({c["page"] for c in layout})
        if "--pages" in a:
            pages = [int(x) for x in a[a.index("--pages") + 1].split(",")]
        shots, errs = shoot_pages(suite, pages, settle)
        for (p, e), m in shots.items():
            m.save(outdir / f"map_p{p}_{e}.png")
        (outdir / "errors.json").write_text(json.dumps(errs))

    rows = []
    for c in layout:
        by, od = shots.get((c["page"], "byond")), shots.get((c["page"], "od"))
        if by is None or od is None:
            continue
        box = cell_box(c["slot"])
        cb, co = by.crop(box), od.crop(box)
        ok, share, mean, heat = compare(cb, co, c["tol"])
        stem = c["id"].replace("#", "_")
        cb.save(outdir / f"{stem}_byond.png"); co.save(outdir / f"{stem}_od.png"); heat.save(outdir / f"{stem}_diff.png")
        rows.append({**c, "ok": ok, "share": share, "mean": mean, "stem": stem,
                     "err_byond": errs.get("byond", {}).get(c["id"]), "err_od": errs.get("od", {}).get(c["id"])})
    rows.sort(key=lambda r: (r["ok"], -r["share"]))
    (outdir / "summary.json").write_text(json.dumps(rows, indent=1))
    write_html(suite, rows, outdir)
    n_ok = sum(r["ok"] for r in rows)
    print(f"\n{suite}: {n_ok}/{len(rows)} cells pass; report {outdir / 'index.html'}")
    for r in rows:
        if not r["ok"]:
            print(f"  FAIL {r['name'][:70]:70} diff px {r['share'] * 100:5.1f}%  mean {r['mean']:.1f}")


def write_html(suite, rows, outdir):
    def esc(x):
        return html.escape(str(x))
    parts = [f"<!doctype html><meta charset=utf-8><title>{esc(suite)} render parity</title>",
             "<style>body{font:13px system-ui;background:#1e1e1e;color:#ddd;margin:16px}img{image-rendering:pixelated;width:192px;height:192px;background:#000}"
             "td{padding:6px;vertical-align:top;border-bottom:1px solid #333}.fail{color:#f77}.ok{color:#7d7}code{color:#9cf;white-space:pre-wrap}</style>",
             f"<h1>{esc(suite)}: {sum(r['ok'] for r in rows)}/{len(rows)} cells pass</h1>",
             "<table><tr><th>cell</th><th>BYOND</th><th>OD</th><th>diff</th></tr>"]
    for r in rows:
        cls = "ok" if r["ok"] else "fail"
        errs = "".join(f"<div class=fail>{e}: {esc(r['err_' + e])}</div>" for e in ("byond", "od") if r.get("err_" + e))
        parts.append(f"<tr><td><b class={cls}>{'PASS' if r['ok'] else 'FAIL'}</b> {esc(r['name'])}<br>"
                     f"diff pixels {r['share'] * 100:.1f}%, mean {r['mean']:.2f}<br>page {r['page']} slot {r['slot']}{errs}</td>"
                     f"<td><img src='{r['stem']}_byond.png'></td><td><img src='{r['stem']}_od.png'></td><td><img src='{r['stem']}_diff.png'></td></tr>")
    parts.append("</table>")
    (outdir / "index.html").write_text("\n".join(parts), encoding="utf-8")


if __name__ == "__main__":
    main(sys.argv[1:])
